/**
 * Grid mapping and DataTexture management for the 50x50 exploration map.
 * World boundaries: X: [-50, 50], Z: [-50, 50], resolution: 2.0 m/cell.
 */

export const DEFAULT_GRID_CONFIG = {
  xMin: -50,
  xMax: 50,
  zMin: -50,
  zMax: 50,
  resolution: 2.0,
  width: 50,
  height: 50,
};

/**
 * Maps world (x, z) coordinates into grid cell indices (ix, iz) and flattened index.
 * Clamps coordinates to valid cell ranges [0, width - 1] and [0, height - 1].
 *
 * @param {number} x
 * @param {number} z
 * @param {object} config
 * @returns {{ ix: number, iz: number, index: number }}
 */
export function worldToCell(x, z, config = DEFAULT_GRID_CONFIG) {
  const { xMin, zMin, resolution, width, height } = config;

  let ix = Math.floor((x - xMin) / resolution);
  let iz = Math.floor((z - zMin) / resolution);

  ix = Math.max(0, Math.min(width - 1, ix));
  iz = Math.max(0, Math.min(height - 1, iz));

  const index = iz * width + ix;
  return { ix, iz, index };
}

/**
 * Maps cell indices (ix, iz) to world center coordinates (x, z).
 *
 * @param {number} ix
 * @param {number} iz
 * @param {object} config
 * @returns {{ x: number, z: number }}
 */
export function cellToWorld(ix, iz, config = DEFAULT_GRID_CONFIG) {
  const { xMin, zMin, resolution } = config;
  const x = xMin + (ix + 0.5) * resolution;
  const z = zMin + (iz + 0.5) * resolution;
  return { x, z };
}

/**
 * Colors for DataTexture RGBA (Uint8ClampedArray):
 * Unexplored: Dark tactical slate [15, 23, 42, 255]
 * Explored: Glowing cyan/emerald [0, 240, 255, 230]
 */
export const COLOR_UNEXPLORED = [15, 23, 42, 255];
export const COLOR_EXPLORED = [0, 240, 255, 240];

/**
 * Creates an initial RGBA buffer (50x50x4 = 10000 bytes) initialized to UNEXPLORED.
 *
 * @param {number} width
 * @param {number} height
 * @returns {Uint8Array}
 */
export function createInitialGridBuffer(width = 50, height = 50) {
  const buffer = new Uint8Array(width * height * 4);
  for (let i = 0; i < width * height; i++) {
    const offset = i * 4;
    buffer[offset] = COLOR_UNEXPLORED[0];
    buffer[offset + 1] = COLOR_UNEXPLORED[1];
    buffer[offset + 2] = COLOR_UNEXPLORED[2];
    buffer[offset + 3] = COLOR_UNEXPLORED[3];
  }
  return buffer;
}

/**
 * Decodes a base64-encoded bitmask (generated by np.packbits) into an array of booleans.
 * NumPy packbits packs with MSB first (bit 7 down to bit 0).
 *
 * @param {string} base64Str
 * @param {number} totalCells
 * @returns {Uint8Array} Binary array (1 = explored, 0 = unexplored)
 */
export function decodeBitmask(base64Str, totalCells = 2500) {
  let binaryStr;
  if (typeof atob === 'function') {
    binaryStr = atob(base64Str);
  } else if (typeof Buffer !== 'undefined') {
    binaryStr = Buffer.from(base64Str, 'base64').toString('binary');
  } else {
    throw new Error('No base64 decoder available in environment');
  }

  const result = new Uint8Array(totalCells);
  let cellIdx = 0;

  for (let byteIdx = 0; byteIdx < binaryStr.length; byteIdx++) {
    const byteVal = binaryStr.charCodeAt(byteIdx);
    for (let bit = 7; bit >= 0; bit--) {
      if (cellIdx < totalCells) {
        result[cellIdx] = (byteVal >> bit) & 1;
        cellIdx++;
      }
    }
  }

  return result;
}

/**
 * Applies a decoded snapshot to the RGBA texture buffer.
 *
 * @param {string} bitmaskBase64
 * @param {Uint8Array} textureBuffer - 50x50x4 RGBA array
 * @param {number} width
 * @param {number} height
 * @returns {number} Explored count
 */
export function applyGridSnapshot(bitmaskBase64, textureBuffer, width = 50, height = 50) {
  const totalCells = width * height;
  const decoded = decodeBitmask(bitmaskBase64, totalCells);
  let exploredCount = 0;

  for (let i = 0; i < totalCells; i++) {
    const offset = i * 4;
    if (decoded[i] === 1) {
      exploredCount++;
      textureBuffer[offset] = COLOR_EXPLORED[0];
      textureBuffer[offset + 1] = COLOR_EXPLORED[1];
      textureBuffer[offset + 2] = COLOR_EXPLORED[2];
      textureBuffer[offset + 3] = COLOR_EXPLORED[3];
    } else {
      textureBuffer[offset] = COLOR_UNEXPLORED[0];
      textureBuffer[offset + 1] = COLOR_UNEXPLORED[1];
      textureBuffer[offset + 2] = COLOR_UNEXPLORED[2];
      textureBuffer[offset + 3] = COLOR_UNEXPLORED[3];
    }
  }

  return exploredCount;
}

/**
 * Applies sparse newly-explored cell indices to the RGBA texture buffer.
 *
 * @param {Array<number>} newCells
 * @param {Uint8Array} textureBuffer
 * @param {number} width
 * @param {number} height
 */
export function applyGridDelta(newCells, textureBuffer, width = 50, height = 50) {
  const totalCells = width * height;
  if (!newCells || !Array.isArray(newCells)) return;

  for (const idx of newCells) {
    if (idx >= 0 && idx < totalCells) {
      const offset = idx * 4;
      textureBuffer[offset] = COLOR_EXPLORED[0];
      textureBuffer[offset + 1] = COLOR_EXPLORED[1];
      textureBuffer[offset + 2] = COLOR_EXPLORED[2];
      textureBuffer[offset + 3] = COLOR_EXPLORED[3];
    }
  }
}
